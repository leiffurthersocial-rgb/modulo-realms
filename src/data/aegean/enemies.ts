const fieldEnemy = ([
  slug,
  name,
  kind,
  level,
  tactic,
  role,
  palette = "aegean_earth",
]: FieldSpec): EnemyDef => ({
  id: `aegean_${slug}`,
  name,
  kind: "creature",
  creature: { kind, palette },
  role,
  level,
  health: enemyHealthAt(level, role),
  damage: enemyDamageAt(level, role),
  defense: enemyDefenseAt(level, role),
  xp: enemyXpAt(level, role),
  gold: enemyGoldAt(level, role),
  speed: role === "skirmisher" ? 116 : role === "brute" ? 69 : 89,
  radius: role === "brute" ? 18 : 13,
  scale: role === "brute" ? 1.7 : 1.25,
  sight: 390,
  attackRange: tactic === "volley" || tactic === "piper" ? 250 : 45,
  attackCooldown: role === "brute" ? 2.3 : 1.65,
  windup: 0.65,
  tactic,
  pack: slug === "hound",
  elite: role === "elite",
  ranged: ["volley", "piper", "lure"].includes(tactic ?? "")
    ? {
        speed: 280,
        element: "arcane",
        color: blue,
        radius: 13,
        count: tactic === "volley" ? 3 : 1,
        arc: 0.3,
      }
    : undefined,
  drops: [
    {
      item: level >= 93 ? "aegean_stygian_glass" : "aegean_bronze",
      chance: 0.24,
    },
  ],
  lootChance: 0.13,
  tags:
    kind === "wraith" || slug === "hoplite"
      ? ["undead"]
      : kind === "automaton"
        ? ["construct"]
        : ["beast"],
});

